enum class ThemeType {
    // The names of the themes must not be changed, since they are used by Preferences for (de)serialization
    Light,
    Dark,
}

enum class BackTransitionDirection {
    LeftToRightOpen,
    RightToLeftOpen,
    FollowSwipeEdge,
}

@Composable
fun ThemeType?.prefersDarkTheme(): Boolean = when (this) {
    null -> isSystemInDarkTheme()
    ThemeType.Light -> false
    ThemeType.Dark -> true
}

@Composable
fun OpenSCQ30Theme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    amoledBlack: Boolean = false,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val configuration = LocalConfiguration.current
    val colorScheme = remember(darkTheme, dynamicColor, amoledBlack, configuration, context) {
        val baseColorScheme = when {
            dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
                if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
            }

            darkTheme -> darkColorScheme

            else -> lightColorScheme
        }
        if (darkTheme && amoledBlack) {
            baseColorScheme.withAmoledBlack()
        } else {
            baseColorScheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}

@Composable
fun OpenSCQ30GlanceTheme(dynamicColor: Boolean = true, content: @Composable () -> Unit) {
    GlanceTheme(
        colors = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S && dynamicColor) {
            GlanceTheme.colors
        } else {
            ColorProviders(light = lightColorScheme, dark = darkColorScheme)
        },
    ) {
        content()
    }
}
